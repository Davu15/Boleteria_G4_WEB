<?php
declare(strict_types=1);

/** PNG RGB sin GD: mismas barras 2/5 px, márgenes y alto de la utilidad Java. */
class ImagenPNG {
    public static function codigo(string $codigo): string {
        $patrones = CodigoBarras39::patrones($codigo);
        $barras = [];
        $x = 20;
        foreach ($patrones as $patron) {
            foreach (str_split($patron) as $i => $p) {
                $w = $p === 'w'?5:2;
                if ($i % 2 === 0) $barras[] = [$x, $w];
                $x += $w;
            }
            $x += 2;
        }
        $width = $x+20;
        $height = 115;
        $glyphs = [
            '0' => '01110100011001110101110011000101110',
            '1' => '00100011000010000100001000010001110',
            '2' => '01110100010000100010001000100011111',
            '3' => '11110000010000101110000010000111110',
            '4' => '00010001100101010010111110001000010',
            '5' => '11111100001000011110000010000111110',
            '6' => '01110100001000011110100011000101110',
            '7' => '11111000010001000100010000100001000',
            '8' => '01110100011000101110100011000101110',
            '9' => '01110100011000101111000010000101110',
            'A' => '01110100011000111111100011000110001',
            'B' => '11110100011000111110100011000111110',
            'C' => '01111100001000010000100001000001111',
            'D' => '11110100011000110001100011000111110',
            'E' => '11111100001000011110100001000011111',
            'F' => '11111100001000011110100001000010000',
            'G' => '01111100001000010111100011000101111',
            'H' => '10001100011000111111100011000110001',
            'I' => '01110001000010000100001000010001110',
            'J' => '00001000010000100001100011000101110',
            'K' => '10001100101010011000101001001010001',
            'L' => '10000100001000010000100001000011111',
            'M' => '10001110111010110101100011000110001',
            'N' => '10001110011010110011100011000110001',
            'O' => '01110100011000110001100011000101110',
            'P' => '11110100011000111110100001000010000',
            'Q' => '01110100011000110001101011001001101',
            'R' => '11110100011000111110101001001010001',
            'S' => '01111100001000001110000010000111110',
            'T' => '11111001000010000100001000010000100',
            'U' => '10001100011000110001100011000101110',
            'V' => '10001100011000110001100010101000100',
            'W' => '10001100011000110101101011010101010',
            'X' => '10001100010101000100010101000110001',
            'Y' => '10001100010101000100001000010000100',
            'Z' => '11111000010001000100010001000011111',
            '-' => '00000000000000011111000000000000000',
            '.' => '00000000000000000000000000011000110',
            ' ' => str_repeat('0', 35)
        ];
        $label = strtoupper($codigo);
        $labelX = (int)(($width-strlen($label)*12) / 2);
        $raw = '';
        for ($y = 0;$y < $height;$y++) {
            $row = str_repeat("\xff\xff\xff", $width);
            if ($y >= 10 && $y < 80) foreach ($barras as [$left, $w]) $row = substr_replace($row, str_repeat("\0", $w*3), $left*3, $w*3);
            if ($y >= 85 && $y < 99) {
                $gy = intdiv($y-85, 2);
                foreach (str_split($label) as $i => $char) {
                    $glyph = $glyphs[$char] ?? $glyphs[' '];
                    for ($gx = 0;$gx < 5;$gx++) if ($glyph[$gy*5+$gx] === '1') $row = substr_replace($row, str_repeat("\0", 6), ($labelX+$i*12+$gx*2)*3, 6);
                }
            }
            $raw .= "\0" . $row;
        }
        return "\x89PNG\r\n\x1a\n" . self::chunk('IHDR', pack('NNCCCCC', $width, $height, 8, 2, 0, 0, 0)) . self::chunk('IDAT', gzcompress($raw)) . self::chunk('IEND', '');
    }

    private static function chunk(string $tipo, string $datos): string {
        return pack('N', strlen($datos)) . $tipo . $datos . pack('N', crc32($tipo . $datos));
    }
}
